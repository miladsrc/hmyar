#!/usr/bin/env python3
"""Generate a deterministic daily report (no LLM required).

Usage:
    python scripts/daily_report.py --date YYYY-MM-DD [--out DIR]

Writes memory/daily/YYYY-MM-DD.md (or DIR/YYYY-MM-DD.md). Does not overwrite
an existing report unless --force is given (avoids clobbering historical evidence).
"""
import argparse
import datetime
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def git(*args):
    try:
        out = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True)
        return out.stdout.strip()
    except Exception:
        return ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", default=datetime.date.today().isoformat())
    ap.add_argument("--out", default=os.path.join(ROOT, "memory", "daily"))
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    os.makedirs(args.out, exist_ok=True)
    target = os.path.join(args.out, f"{args.date}.md")
    if os.path.exists(target) and not args.force:
        print(f"Report already exists: {target} (use --force to overwrite)")
        sys.exit(0)

    commits = git("log", "--since", f"{args.date} 00:00", "--until", f"{args.date} 23:59:59",
                  "--pretty=format:- %h %s (%an)")
    status = git("status", "--short")
    branch = git("rev-parse", "--abbrev-ref", "HEAD")

    lines = []
    lines.append(f"# Daily Report - {args.date}")
    lines.append("")
    lines.append("Generated by `scripts/daily_report.py` (deterministic; no LLM summarization).")
    lines.append("")
    lines.append("## Context")
    lines.append("")
    lines.append(f"- Branch: {branch}")
    lines.append(f"- Generated at: {datetime.datetime.now().isoformat(timespec='seconds')}")
    lines.append("")
    lines.append("## Commits in window")
    lines.append("")
    lines.append(commits if commits else "(none)")
    lines.append("")
    lines.append("## Working tree status")
    lines.append("")
    lines.append("```")
    lines.append(status if status else "(clean)")
    lines.append("```")
    lines.append("")
    lines.append("## Knowledge changes")
    lines.append("")
    lines.append("(Record manually or via PR review: what changed, evidence, decisions, blockers, next steps.)")
    lines.append("")
    lines.append("## LLM summarization")
    lines.append("")
    lines.append("Not configured (provider = none). Set `llm.provider` in config/hmyar.yaml to enable.")
    lines.append("")

    with open(target, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {target}")


if __name__ == "__main__":
    main()
